// Netlify build step for the static marketing site.
// Writes api-config.js from STW_API_BASE so coming-soon.html has no hardcoded API origin.
//
//   STW_API_BASE=http://127.0.0.1:43147 node inject-api-base.mjs
//   node inject-api-base.mjs --out /tmp/api-config.js
//
// Unset or blank STW_API_BASE keeps the production origin (also set in netlify.toml).

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const DEFAULT_API_BASE = "https://api.splitthewine.app";

const here = dirname(fileURLToPath(import.meta.url));
export const defaultConfigPath = join(here, "api-config.js");

/** Absolute http(s) origin, no path, query, hash, or credentials. Blank → production default. */
export function resolveApiBase(raw) {
  const value = (raw ?? "").trim();
  if (!value) return DEFAULT_API_BASE;
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new Error(`STW_API_BASE is not an absolute URL: ${value}`);
  }
  if (url.protocol !== "https:" && url.protocol !== "http:") {
    throw new Error(`STW_API_BASE must be http(s), got ${url.protocol}`);
  }
  if (url.username || url.password) {
    throw new Error("STW_API_BASE must not include credentials");
  }
  if (url.pathname !== "/" && url.pathname !== "") {
    throw new Error(`STW_API_BASE must be an origin with no path, got ${url.pathname}`);
  }
  if (url.search || url.hash) {
    throw new Error("STW_API_BASE must not include a query or hash");
  }
  return url.origin;
}

export function renderApiConfig(origin) {
  return `// Generated by inject-api-base.mjs — do not edit by hand.
// Netlify rewrites this file from STW_API_BASE on each build.
// The committed copy is the production default so a publish without that build still works.
window.STW_API_BASE = ${JSON.stringify(origin)};
`;
}

export function injectApiBase({ env = process.env, outPath = defaultConfigPath } = {}) {
  const raw = env.STW_API_BASE ?? "";
  const origin = resolveApiBase(raw);
  writeFileSync(outPath, renderApiConfig(origin), "utf8");
  return origin;
}

function outPathFromArgv(argv) {
  const index = argv.indexOf("--out");
  if (index === -1) return defaultConfigPath;
  const value = argv[index + 1];
  if (!value) throw new Error("--out requires a file path");
  return value;
}

function isDirectRun() {
  const entry = process.argv[1];
  if (!entry) return false;
  return import.meta.url === pathToFileURL(entry).href;
}

if (isDirectRun()) {
  try {
    const origin = injectApiBase({ outPath: outPathFromArgv(process.argv) });
    const source = (process.env.STW_API_BASE ?? "").trim()
      ? "STW_API_BASE"
      : "production default (STW_API_BASE unset)";
    console.log(`inject-api-base: ${origin} (${source})`);
  } catch (err) {
    console.error(err instanceof Error ? err.message : String(err));
    process.exit(1);
  }
}
